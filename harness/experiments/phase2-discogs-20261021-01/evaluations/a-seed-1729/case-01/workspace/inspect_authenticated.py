def run(h):
    read = {'disposition':'accepted','effects':{'persistent_state_changed':False,'affected_record_count':0},'ui_claims':[],'unknowns':[]}
    h.expect(read, 'Inspect login page linked by Account')
    h.page.goto(h.origin + '/login')
    print(h.observe('login-form'))
    password = h.page.locator('input[type="password"]')
    form = h.page.locator('form').filter(has=password)
    h.expect(read, 'Set supplied fixture username without exposing its value')
    form.locator('input').first.fill(h.fixture['account']['username'])
    h.expect(read, 'Set supplied fixture password without exposing its value')
    password.fill(h.fixture['account']['password'])
    h.expect({'disposition':'accepted','effects':{'persistent_state_changed':False,'affected_record_count':0},'ui_claims':['Sign in reaches home; Account button appears'],'unknowns':['Only supplied valid account was learned']}, 'Authenticate once using supplied fixture, supported by frozen R001')
    h.page.get_by_role('button',name='Sign in',exact=True).click()
    print(h.observe('authenticated-home'))
    h.expect(read, 'Read existing collection baseline using learned collection route')
    h.page.goto(h.origin + '/me/collection')
    print(h.observe('collection-before'))
    print({'authenticated':h.page.get_by_role('button',name='Account',exact=True).count()==1, 'target_collection_link_count':h.page.locator('main a[href="/release/1"]').count()})
    h.expect(read, 'Inspect task-specified release 1 using learned public release route')
    h.page.goto(h.origin + '/release/1')
    print(h.observe('target-release-before'))
